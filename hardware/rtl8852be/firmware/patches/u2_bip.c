static byte twice(byte x) { return (byte)((x << 1) ^ ((x >> 7) * 0x1b)); }
static void aes(const struct u2_cmac_key *key, byte state[16]) {
    byte shifted[16];
    for (unsigned i=0;i<16;i++) state[i]^=key->round[i];
    for (unsigned round=1;round<=10;round++) {
        for (unsigned col=0;col<4;col++)
            for (unsigned row=0;row<4;row++)
                shifted[4*col+row]=sbox[state[4*((col+row)&3)+row]];
        for (unsigned col=0;col<4;col++) {
            const byte *s=shifted+4*col;
            byte sum=s[0]^s[1]^s[2]^s[3];
            for (unsigned row=0;row<4;row++) {
                byte value=s[row];
                if (round<10) value^=sum^twice(s[row]^s[(row+1)&3]);
                state[4*col+row]=value^key->round[16*round+4*col+row];
            }
        }
    }
}
static void double_block(const byte in[16],byte out[16]) {
    byte reduction=(in[0]>>7)*0x87;
    for (unsigned i=0;i<15;i++) out[i]=(byte)((in[i]<<1)|(in[i+1]>>7));
    out[15]=(byte)((in[15]<<1)^reduction);
}
void u2_cmac_key(struct u2_cmac_key *key,const byte input[16]) {
    for (unsigned i=0;i<16;i++) key->round[i]=input[i];
    byte rc=1;
    for (unsigned at=16;at<176;at+=4) {
        byte word[4];
        for (unsigned i=0;i<4;i++) word[i]=key->round[at-4+i];
        if (!(at&15)) {
            byte first=word[0];
            word[0]=sbox[word[1]]^rc;
            word[1]=sbox[word[2]];
            word[2]=sbox[word[3]];
            word[3]=sbox[first];
            rc=twice(rc);
        }
        for (unsigned i=0;i<4;i++) key->round[at+i]=key->round[at-16+i]^word[i];
    }
    byte block[16]={0};
    aes(key,block);
    double_block(block,key->subkey[0]);
    double_block(key->subkey[0],key->subkey[1]);
}
struct cmac {
    byte state[16],block[16];
    unsigned used;
};
static void update(const struct u2_cmac_key *key,struct cmac *c,
                   const byte *data,unsigned length) {
    for (unsigned i=0;i<length;i++) {
        if (c->used==16) {
            for (unsigned j=0;j<16;j++) c->state[j]^=c->block[j];
            aes(key,c->state);
            c->used=0;
        }
        c->block[c->used++]=data[i];
    }
}
static void finish(const struct u2_cmac_key *key,struct cmac *c) {
    const byte *subkey=key->subkey[c->used!=16];
    if (c->used<16) {
        c->block[c->used++]=0x80;
        while (c->used<16) c->block[c->used++]=0;
    }
    for (unsigned i=0;i<16;i++) c->state[i]^=c->block[i]^subkey[i];
    aes(key,c->state);
}
void u2_cmac(const struct u2_cmac_key *key,const byte *data,unsigned length,
             byte mac[16]) {
    struct cmac c={0};
    update(key,&c,data,length);
    finish(key,&c);
    for (unsigned i=0;i<16;i++) mac[i]=c.state[i];
}
void u2_beacon_mic(const struct u2_cmac_key *key,const byte *frame,
                   unsigned length,byte mic[8]) {
    struct cmac c={0};
    byte aad[20];
    static const byte zero[8]={0};
    aad[0]=frame[0];aad[1]=frame[1]&~0x38;
    for (unsigned i=0;i<18;i++) aad[2+i]=frame[4+i];
    update(key,&c,aad,20);
    update(key,&c,zero,8);
    update(key,&c,frame+32,length-40);
    update(key,&c,zero,8);
    finish(key,&c);
    for (unsigned i=0;i<8;i++) mic[i]=c.state[i];
}
